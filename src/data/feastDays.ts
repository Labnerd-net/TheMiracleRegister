export function getFixedFeasts(month: number, day: number): FixedFeastEntry[] {
  return FIXED_FEASTS.filter((f) => f.month === month && f.day === day);
}

export function getMovableFeast(easterOffset: number): MovableFeastEntry | undefined {
  return MOVABLE_FEASTS.find((f) => f.easterOffset === easterOffset);
}
